/** M7 presentation-only view models. These are NOT API contracts or generated OpenAPI types.
 * The backend/integration adapter must authorize and redact data before constructing these props.
 * No coordinates, driver identities, contact data or notification body fields are accepted.
 */
export type EvidenceQuality = "verified" | "stale" | "missing" | "unknown" | "unavailable";
export type LoadState = "ready" | "loading" | "error";
export type RiskStatus = "ON_TRACK" | "AT_RISK" | "PREDICTED_LATE" | "OVERDUE";

/** A value's quality is explicit: an absent timestamp is not interpreted as on-track. */
export interface TimeDatum {
  at: string | null; // ISO 8601 instant with offset, or null
  quality: EvidenceQuality;
  source?: string | null;
  asOf?: string | null;
}

export interface QuantityDatum {
  value: number | null;
  quality: EvidenceQuality;
  source?: string | null;
  asOf?: string | null;
}

/** Route quality comes from the upstream service, not the vehicle type or ETA. */
export interface Provenance {
  source: string | null;
  asOf?: string | null;
  routeQuality?: "verified_ors" | "estimated_fallback" | "unknown" | null;
}

export interface RiskSummaryModel {
  timeZone: string;
  committedWindow: { start: TimeDatum; end: TimeDatum; confirmedAt?: TimeDatum };
  plannedEta: TimeDatum;
  forecastEta: TimeDatum;
  reserveConsumptionPct: QuantityDatum;
  risk: { status: RiskStatus | null; quality: EvidenceQuality };
  forecastProvenance?: Provenance | null;
}

export type MilestoneKind =
  | "APPROVED"
  | "START_PREP"
  | "GOODS_READY"
  | "LOADED"
  | "DISPATCHED"
  | "DELIVERED";

export interface MilestoneRecord {
  kind: MilestoneKind;
  planned?: TimeDatum | null;
  actual?: TimeDatum | null;
  forecast?: TimeDatum | null;
}

export interface MilestoneTimelineModel {
  timeZone: string;
  milestones: MilestoneRecord[]; // missing kind is rendered explicitly as unavailable evidence
  asOf?: TimeDatum | null;
}

export type VehicleExecutionState = "LOADED" | "DISPATCHED" | "DELIVERED" | "FAILED" | "UNKNOWN";

export interface VehicleExecution {
  tripReference: string;
  vehicleCode: string;
  state: VehicleExecutionState;
  stateQuality: EvidenceQuality;
  latestEventAt?: TimeDatum | null;
  forecastEta?: TimeDatum | null;
}

export interface VehicleStatusModel {
  timeZone: string;
  /** Supplied by backend for the ORDER; never derived from vehicle rows. */
  overallForecastEta: TimeDatum;
  vehicles: VehicleExecution[];
  forecastProvenance?: Provenance | null;
}

export interface RiskExplanationModel {
  risk: { status: RiskStatus | null; quality: EvidenceQuality };
  /** Upstream rule-based explanation, NOT generated by frontend. */
  explanation: string | null;
  reasonCodes: string[];
  provenance: Provenance | null;
}

export interface OrderEvent {
  eventId: string;
  eventAt: TimeDatum;
  eventType: string;
  /** A server-authorized role label only; never a driver name or contact. */
  actorRole: string | null;
  /** Server-authorized, non-PII effect summary; never raw event payload. */
  effect: string | null;
}

export interface OrderEventLogModel {
  timeZone: string;
  events: OrderEvent[];
}

export type NotificationType = "CONFIRMED" | "DISPATCHED" | "DELIVERED" | "FAILED" | "DELAY";
export type NotificationChannel = "email" | "sms_sim";
export type NotificationStatus = "draft" | "queued" | "sent" | "failed" | "suppressed";

export interface NotificationItem {
  notificationId: string;
  type: NotificationType;
  channel: NotificationChannel;
  status: NotificationStatus;
  timestamp: TimeDatum;
}

export interface NotificationHistoryModel {
  timeZone: string;
  notifications: NotificationItem[];
}

/** Shared panel state: upstream provides loading/error status, never fetched here. */
export interface PanelStateProps {
  loadState?: LoadState;
  errorReference?: string | null; // correlation ID only; no raw backend error/PII
  className?: string;
}
